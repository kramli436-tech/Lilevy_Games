function New-Section([byte]$id, [byte[]]$payload) {
    $sec = [System.Collections.Generic.List[byte]]::new()
    $sec.Add($id)
    
    $v = $payload.Length
    do {
        $b = $v -band 0x7F
        $v = $v -shr 7
        if ($v -ne 0) { $b = $b -bor 0x80 }
        $sec.Add([byte]$b)
    } while ($v -ne 0)
    
    foreach ($b in $payload) { $sec.Add([byte]$b) }
    return $sec.ToArray()
}

